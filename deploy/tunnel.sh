#!/usr/bin/env bash
# Пробрасывает порты JARVIS с сервера на этот Mac.
#
#   ./tunnel.sh логин@адрес
#
# Пока команда работает, http://localhost:5173 на этом Mac — это JARVIS
# на сервере. Браузер видит localhost, поэтому микрофон работает без
# сертификатов, а наружу на сервере ничего открывать не нужно.
#
# Остановить — Ctrl-C.

set -euo pipefail

REMOTE="${1:-}"

# Порт моста НА СЕРВЕРЕ. На этом Mac он всегда виден как 8787, потому что
# фронтенд по умолчанию ищет мост именно там; туннель сопоставляет разные
# номера, так что настраивать фронтенд не нужно.
BRIDGE_PORT="${JARVIS_BRIDGE_PORT:-8790}"

# Порт SSH на сервере. 22 бывает закрыт по дороге — у провайдера или в сети
# между вами, — и тогда соединение не отвергается, а молча висит до таймаута.
# Если сервер слушает запасной порт, укажи его здесь.
SSH_PORT="${JARVIS_SSH_PORT:-22}"

if [ -z "$REMOTE" ]; then
  echo "Использование: $0 логин@адрес" >&2
  echo "Порт моста на сервере: JARVIS_BRIDGE_PORT (сейчас $BRIDGE_PORT)" >&2
  exit 2
fi

# Занятый локальный порт — самая частая причина "туннель есть, а страницы нет":
# ssh напишет про это одну строку и продолжит работать вхолостую.
for port in 5173 8787; do
  holder=$(lsof -nP -iTCP:"$port" -sTCP:LISTEN 2>/dev/null | tail -n +2) || true
  [ -z "$holder" ] && continue

  # Чаще всего порт держит уже поднятый туннель, а не что-то постороннее, и
  # совет «останови локальный JARVIS» в этом случае только сбивает с толку.
  if printf '%s\n' "$holder" | grep -q '^ssh '; then
    echo "Туннель уже поднят — второй не нужен." >&2
    echo "Открывай: http://localhost:5173" >&2
    echo >&2
    echo "Если нужен именно перезапуск, закрой прежний (Ctrl-C в его вкладке) и повтори." >&2
    exit 0
  fi

  echo "Порт $port на этом Mac занят другим процессом:" >&2
  printf '%s\n' "$holder" | sed 's/^/  /' >&2
  echo >&2
  echo "Похоже на локальный JARVIS. Останови его и запусти туннель снова." >&2
  exit 1
done

echo "Пробрасываю интерфейс 5173→5173 и мост 8787→$BRIDGE_PORT с $REMOTE (ssh-порт $SSH_PORT)"
echo "Открой в Chrome: http://localhost:5173"
echo "Ctrl-C — закрыть туннель."
echo

# -N  ничего не выполнять на сервере, только форвардинг
# ExitOnForwardFailure  упасть сразу, если порт пробросить не удалось,
#                       а не висеть молча
exec ssh -N \
  -p "$SSH_PORT" \
  -o ExitOnForwardFailure=yes \
  -o ServerAliveInterval=30 \
  -L 5173:localhost:5173 \
  -L "8787:localhost:$BRIDGE_PORT" \
  "$REMOTE"
